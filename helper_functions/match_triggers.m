%%
function prefix_count = matching_terminal_prefix_count( ...
    eeg_event_table, eeg_Fs, eeg_event_indices, ...
    edf_event_table, edf_Fs, edf_event_indices, tolerance_sec)

max_prefix_count = min(numel(eeg_event_indices), numel(edf_event_indices));
eeg_event_indices = eeg_event_indices(1:max_prefix_count);
edf_event_indices = edf_event_indices(1:max_prefix_count);
eeg_type = strip(string(eeg_event_table.type(eeg_event_indices)));
edf_type = strip(string(edf_event_table.type(edf_event_indices)));
eeg_latency = double(eeg_event_table.latency(eeg_event_indices));
edf_latency = double(edf_event_table.latency(edf_event_indices));
eeg_interval_sec = diff(eeg_latency) ./ eeg_Fs;
edf_interval_sec = diff(edf_latency) ./ edf_Fs;
comparison_scale = max([ ...
    abs(eeg_interval_sec), abs(edf_interval_sec), ...
    ones(size(eeg_interval_sec))], [], 2);
roundoff_tolerance_sec = 10 * eps(comparison_scale);

trigger_matches = eeg_type == edf_type;
trigger_matches(2:end) = trigger_matches(2:end) & ...
    abs(eeg_interval_sec - edf_interval_sec) <= ...
        tolerance_sec + roundoff_tolerance_sec;
first_mismatch = find(~trigger_matches, 1, 'first');
if isempty(first_mismatch)
    prefix_count = max_prefix_count;
else
    prefix_count = first_mismatch - 1;
end

end

