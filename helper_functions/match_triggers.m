%%
function [eeg_color, edf_color, terminal_color] = ...
    trigger_chunk_colors(result, eeg_input, edf_input)

eeg_color = zeros(height(eeg_input.event_table), 3);
edf_color = zeros(height(edf_input.event_table), 3);
terminal_color = [0, 0, 0];
history = result.comparison_history;
trusted_outcomes = [ ...
    "match", "partial_start_match", "shared_trigger_glitch", ...
    "eeg_shorter", "eeg_longer", "same_last_trigger"];
trusted_history_index = find(ismember(history.outcome, trusted_outcomes));
color_map = lines(numel(trusted_history_index));

for color_i = 1:numel(trusted_history_index)
    history_i = trusted_history_index(color_i);
    color = color_map(color_i, :);
    outcome = history.outcome(history_i);
    eeg_chunk_i = history.eeg_chunk_index(history_i);
    edf_chunk_i = history.edf_chunk_index(history_i);
    eeg_start = eeg_input.chunk_report.start_event_index(eeg_chunk_i);
    edf_start = edf_input.chunk_report.start_event_index(edf_chunk_i);

    is_partial_start = outcome == "partial_start_match";
    is_terminal = ismember( ...
        outcome, ["eeg_shorter", "eeg_longer", "same_last_trigger"]);
    if is_partial_start
        eeg_start = result.eeg_initial_anchor_event_index;
        edf_start = result.edf_initial_anchor_event_index;
        eeg_end = eeg_input.chunk_report.end_event_index(eeg_chunk_i);
        edf_end = edf_input.chunk_report.end_event_index(edf_chunk_i);
    elseif is_terminal
        eeg_end = result.eeg_terminal_anchor_event_index;
        edf_end = result.edf_terminal_anchor_event_index;
        terminal_color = color;
        if outcome == "eeg_shorter"
            edf_end = height(edf_input.event_table);
        end
    else
        eeg_end = eeg_input.chunk_report.end_event_index(eeg_chunk_i);
        edf_end = edf_input.chunk_report.end_event_index(edf_chunk_i);
    end

    eeg_color(eeg_start:eeg_end, :) = repmat( ...
        color, eeg_end - eeg_start + 1, 1);
    edf_color(edf_start:edf_end, :) = repmat( ...
        color, edf_end - edf_start + 1, 1);
end

end

