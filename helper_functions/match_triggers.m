function [result, eeg_input, edf_input, figure_handle] = match_triggers( ...
    eeg_input, edf_input, plot_alignment)
%MATCH_TRIGGERS Match EEG/EDF trigger chunks and resolve supported gaps.
%   [RESULT, EEG_INPUT, EDF_INPUT] = MATCH_TRIGGERS(EEG_INPUT, EDF_INPUT)
%   extracts and validates each system's canonical trigger cycle before
%   matching chunks. EEG_INPUT must contain event_table and Fs; EDF_INPUT
%   must contain event_table and trigger_Fs.
%   The optional fourth output is the alignment figure handle when plotting
%   is enabled, or an empty graphics array otherwise.
%   MATCH_TRIGGERS(..., PLOT_ALIGNMENT) creates a three-panel trigger timeline
%   when PLOT_ALIGNMENT is true. The aligned EEG panel applies one shift that
%   places the initial EEG anchor on the initial EDF anchor.
%   EEG and EDF chunk indices advance independently after a discrepancy so
%   matching can resume after a short loss or one missed cycle boundary.
%   Missing-period bounds are trustworthy trigger anchors; data strictly
%   between the anchors is unsafe, while the anchor samples remain valid.
%   When EEG_INPUT.amplifier_interruptions is present, each marked bracket
%   is audited against the EDF reference. A one-interval bracket within
%   tolerance is retained; otherwise the bracket is excluded and matching
%   resumes only after a confirmed post-reconnect interval.
%   The returned event tables mark the terminal region with is_terminal
%   and its last corresponding trigger with is_terminal_alignment_anchor.
%   EDF triggers before an inferred restart alignment are marked
%   is_pre_alignment.

if nargin < 3
    plot_alignment = false;
end
figure_handle = gobjects(0);

validate_system_inputs(eeg_input, edf_input)
eeg_event_table = eeg_input.event_table;
edf_event_table = edf_input.event_table;
eeg_Fs = eeg_input.Fs;
edf_Fs = edf_input.trigger_Fs;
[startup_mode, edf_cycle_start_event_index] = ...
    classify_edf_startup(edf_input, height(edf_event_table));

% Use one shared tolerance for extracting and comparing both cycles. This
% is equivalent to two samples at the lower of the two sampling rates.
interval_tolerance_sec = 2 / min([eeg_Fs, edf_Fs]);

[eeg_canonical_cycle, eeg_repeat_count, eeg_chunk_report] = ...
    extract_canonical_cycle( ...
        eeg_event_table, eeg_Fs, interval_tolerance_sec);
[edf_canonical_cycle, edf_repeat_count, edf_chunk_report] = ...
    extract_cycle_subset( ...
        edf_event_table, edf_Fs, interval_tolerance_sec, ...
        edf_cycle_start_event_index);
validate_canonical_cycles( ...
    eeg_canonical_cycle, edf_canonical_cycle, interval_tolerance_sec);
eeg_canonical_edges = extract_canonical_edges(eeg_canonical_cycle);
edf_canonical_edges = extract_canonical_edges(edf_canonical_cycle);

eeg_input.canonical_cycle = eeg_canonical_cycle;
eeg_input.canonical_repeat_count = eeg_repeat_count;
eeg_input.chunk_report = eeg_chunk_report;
edf_input.canonical_cycle = edf_canonical_cycle;
edf_input.canonical_repeat_count = edf_repeat_count;
edf_input.chunk_report = edf_chunk_report;

validate_chunk_reports(eeg_chunk_report, edf_chunk_report)
if eeg_chunk_report.status(1) == "partial_start"
    error('match_triggers:UnexpectedEegPartialStart', ...
        ['HD-EEG must begin at an intact four-64 cycle boundary; only the ' ...
         'EDF recording supports partial-cycle late-start alignment.'])
end

result = initialize_result;
result.interval_tolerance_sec = interval_tolerance_sec;
result.startup_mode = startup_mode;
[amplifier_interruptions, has_amplifier_interruptions] = ...
    initialize_amplifier_interruptions(eeg_input);
result.amplifier_interruptions = amplifier_interruptions;
eeg_event_table.is_pre_alignment = false(height(eeg_event_table), 1);
edf_event_table.is_pre_alignment = false(height(edf_event_table), 1);
eeg_event_table.is_initial_alignment_anchor = ...
    false(height(eeg_event_table), 1);
edf_event_table.is_initial_alignment_anchor = ...
    false(height(edf_event_table), 1);
eeg_event_table.is_terminal = false(height(eeg_event_table), 1);
edf_event_table.is_terminal = false(height(edf_event_table), 1);
eeg_event_table.is_terminal_alignment_anchor = ...
    false(height(eeg_event_table), 1);
edf_event_table.is_terminal_alignment_anchor = ...
    false(height(edf_event_table), 1);

if startup_mode == "restart_at_last_validation"
    result.edf_leading_restart_inferred = true;
    result.edf_pre_alignment_event_count = ...
        edf_cycle_start_event_index - 1;
    result.initial_alignment_reason = "restart_at_last_validation";
    edf_event_table.is_pre_alignment( ...
        1:result.edf_pre_alignment_event_count) = true;
    validate_post_validation_restart( ...
        eeg_event_table, eeg_Fs, eeg_chunk_report, ...
        edf_event_table, edf_Fs, edf_chunk_report, ...
        interval_tolerance_sec);
elseif startup_mode == "normal_validation_start"
    result.initial_alignment_reason = "normal_validation_start";
end

if edf_chunk_report.status(1) == "partial_start"
    if any(startup_mode == ...
            ["normal_validation_start", "restart_at_last_validation"])
        error('match_triggers:UnexpectedPostValidationPartialStart', ...
            ['The first retained post-validation EDF trigger is not an ' ...
             'intact four-64 boundary.'])
    elseif startup_mode ~= "no_validation"
        error('match_triggers:PartialStartRequiresValidationMetadata', ...
            ['EDF validation metadata is required before a partial-cycle ' ...
             'late start can be accepted.'])
    end
    [result, eeg_initial_anchor_event_index, ...
        edf_initial_anchor_event_index] = resolve_partial_start( ...
            result, eeg_event_table, eeg_Fs, eeg_chunk_report, ...
            edf_event_table, edf_Fs, ...
            edf_chunk_report, edf_canonical_edges, ...
            interval_tolerance_sec);
    eeg_chunk_i = 2;
    edf_chunk_i = 2;
    eeg_event_table.is_pre_alignment( ...
        1:eeg_initial_anchor_event_index - 1) = true;
    result.eeg_pre_alignment_event_count = ...
        eeg_initial_anchor_event_index - 1;
elseif startup_mode == "no_validation"
    error('match_triggers:UnsupportedNoValidationStart', ...
        ['EDF contains no validation sequence and does not begin with a ' ...
         'regular-63 partial cycle. Initial alignment is unsupported.'])
else
    eeg_chunk_i = 1;
    [result, edf_chunk_i, edf_event_table] = resolve_initial_alignment( ...
        result, eeg_event_table, eeg_Fs, eeg_chunk_report, ...
        edf_event_table, edf_Fs, edf_canonical_edges, edf_chunk_report, ...
        interval_tolerance_sec);
    eeg_initial_anchor_event_index = eeg_chunk_report.start_event_index(1);
    edf_initial_anchor_event_index = ...
        edf_chunk_report.start_event_index(edf_chunk_i);
end
if has_amplifier_interruptions
    [result, amplifier_interruptions, ...
        eeg_initial_anchor_event_index, edf_initial_anchor_event_index, ...
        eeg_event_table] = resolve_leading_amplifier_interruption( ...
            result, amplifier_interruptions, ...
            eeg_initial_anchor_event_index, edf_initial_anchor_event_index, ...
            eeg_event_table, eeg_Fs, eeg_chunk_report, ...
            edf_event_table, edf_Fs, edf_chunk_report, ...
            result.initial_edf_chunk_index, ...
            interval_tolerance_sec);
    if result.startup_mode == "partial_cycle_late_start"
        amplifier_interruptions = ...
            resolve_skipped_partial_start_interruptions( ...
                amplifier_interruptions, eeg_initial_anchor_event_index, ...
                eeg_chunk_report, height(eeg_event_table));
        result.eeg_pre_alignment_event_count = ...
            eeg_initial_anchor_event_index - 1;
    end
    result.amplifier_interruptions = amplifier_interruptions;
end
eeg_event_table.is_initial_alignment_anchor( ...
    eeg_initial_anchor_event_index) = true;
edf_event_table.is_initial_alignment_anchor( ...
    edf_initial_anchor_event_index) = true;
result.eeg_initial_anchor_event_index = eeg_initial_anchor_event_index;
result.edf_initial_anchor_event_index = edf_initial_anchor_event_index;
result.eeg_initial_anchor_latency = ...
    double(eeg_event_table.latency(eeg_initial_anchor_event_index));
result.edf_initial_anchor_latency = ...
    double(edf_event_table.latency(edf_initial_anchor_event_index));
edf_input.startup_mode = result.startup_mode;
fprintf('EDF startup mode: %s\n', result.startup_mode);

while eeg_chunk_i <= height(eeg_chunk_report) && ...
        edf_chunk_i <= height(edf_chunk_report)
    if has_amplifier_interruptions
        [terminal_group_ids, amplifier_interruptions] = ...
            terminal_amplifier_groups( ...
                amplifier_interruptions, eeg_chunk_report, eeg_chunk_i, ...
                height(eeg_event_table));
        if ~isempty(terminal_group_ids)
            [result, eeg_event_table, edf_event_table, ...
                amplifier_interruptions] = ...
                align_terminal_amplifier_loss( ...
                    result, terminal_group_ids, amplifier_interruptions, ...
                    eeg_chunk_i, edf_chunk_i, ...
                    eeg_event_table, eeg_Fs, eeg_chunk_report, ...
                    edf_event_table, edf_Fs, edf_chunk_report, ...
                    interval_tolerance_sec);
            result.amplifier_interruptions = amplifier_interruptions;
            break
        end
    end

    is_terminal_region = ...
        ~eeg_chunk_report.has_next_boundary(eeg_chunk_i) || ...
        ~edf_chunk_report.has_next_boundary(edf_chunk_i);
    if has_amplifier_interruptions && is_terminal_region
        eeg_terminal_edges = extract_chunk_edges( ...
            eeg_event_table, eeg_Fs, eeg_chunk_report, eeg_chunk_i);
        edf_terminal_edges = extract_chunk_edges( ...
            edf_event_table, edf_Fs, edf_chunk_report, edf_chunk_i);
        eeg_terminal_status = eeg_chunk_report.status(eeg_chunk_i);
        edf_terminal_status = edf_chunk_report.status(edf_chunk_i);
        [result, amplifier_interruptions, marker_action] = ...
            resolve_amplifier_interruptions_in_chunk( ...
                result, amplifier_interruptions, ...
                eeg_chunk_i, edf_chunk_i, ...
                eeg_event_table, eeg_Fs, eeg_chunk_report, ...
                eeg_terminal_edges, ...
                edf_event_table, edf_chunk_report, edf_terminal_edges, ...
                eeg_terminal_status, edf_terminal_status, ...
                interval_tolerance_sec);
        result.amplifier_interruptions = amplifier_interruptions;
        if marker_action == "advance"
            [result, eeg_event_table, edf_event_table] = ...
                finalize_terminal_amplifier_relock( ...
                    result, eeg_chunk_i, edf_chunk_i, ...
                    eeg_event_table, eeg_chunk_report, ...
                    edf_event_table, edf_chunk_report);
            break
        elseif marker_action == "stop"
            break
        end
    end

    if ~eeg_chunk_report.has_next_boundary(eeg_chunk_i) || ...
            ~edf_chunk_report.has_next_boundary(edf_chunk_i)
        terminal_alignment_locked = false;
        if ~isempty(result.comparison_history)
            last_comparison = result.comparison_history(end, :);
            terminal_alignment_locked = any( ...
                last_comparison.outcome == ["match", "shared_trigger_glitch"]);

            % A matching suffix can re-lock a one-sided loss before the
            % immediately following terminal region.
            all_missing_periods_closed = ...
                ~isempty(result.missing_periods) && ...
                all(isfinite( ...
                    result.missing_periods.end_anchor_event_index));
            resolved_same_offset_loss = any( ...
                last_comparison.outcome == ...
                    ["eeg_data_loss", "edf_data_loss"]) && ...
                last_comparison.resolution_status == ...
                    "resumed_same_offset" && ...
                last_comparison.next_eeg_chunk_index == eeg_chunk_i && ...
                last_comparison.next_edf_chunk_index == edf_chunk_i && ...
                ~result.requires_relock && all_missing_periods_closed;
            terminal_alignment_locked = ...
                terminal_alignment_locked || resolved_same_offset_loss;
        end

        if ~terminal_alignment_locked
            error('match_triggers:TerminalAlignmentNotLocked', ...
                ['A matching chunk was not established immediately before ' ...
                 'the terminal region. Terminal anchors cannot be assigned.'])
        end
        [result, eeg_event_table, edf_event_table] = ...
            align_terminal_region( ...
                result, eeg_chunk_i, edf_chunk_i, ...
                eeg_event_table, eeg_Fs, eeg_chunk_report, ...
                edf_event_table, edf_Fs, edf_chunk_report, ...
                interval_tolerance_sec);
        break
    end

    eeg_edges = extract_chunk_edges( ...
        eeg_event_table, eeg_Fs, eeg_chunk_report, eeg_chunk_i);
    edf_edges = extract_chunk_edges( ...
        edf_event_table, edf_Fs, edf_chunk_report, edf_chunk_i);
    pair_matches = edges_match( ...
        eeg_edges, edf_edges, interval_tolerance_sec);

    eeg_status = eeg_chunk_report.status(eeg_chunk_i);
    edf_status = edf_chunk_report.status(edf_chunk_i);
    eeg_matches_canonical = eeg_status == "match";
    edf_matches_canonical = edf_status == "match";

    if has_amplifier_interruptions
        [result, amplifier_interruptions, marker_action] = ...
            resolve_amplifier_interruptions_in_chunk( ...
                result, amplifier_interruptions, ...
                eeg_chunk_i, edf_chunk_i, ...
                eeg_event_table, eeg_Fs, eeg_chunk_report, eeg_edges, ...
                edf_event_table, edf_chunk_report, edf_edges, ...
                eeg_status, edf_status, interval_tolerance_sec);
        result.amplifier_interruptions = amplifier_interruptions;
        if marker_action == "advance"
            eeg_chunk_i = eeg_chunk_i + 1;
            edf_chunk_i = edf_chunk_i + 1;
            continue
        elseif marker_action == "stop"
            break
        end
    end

    if eeg_matches_canonical && edf_matches_canonical
        if ~pair_matches
            error('match_triggers:MatchedChunkDisagreement', ...
                ['EEG chunk %d and EDF chunk %d both match their canonical ' ...
                 'cycles but do not match each other.'], ...
                eeg_chunk_i, edf_chunk_i)
        end

        result = close_open_missing_periods( ...
            result, eeg_chunk_i, edf_chunk_i, ...
            eeg_event_table, eeg_Fs, eeg_chunk_report, ...
            edf_event_table, edf_Fs, edf_chunk_report);
        next_eeg_chunk_i = eeg_chunk_i + 1;
        next_edf_chunk_i = edf_chunk_i + 1;
        result.comparison_history = [result.comparison_history; ...
            make_history_row( ...
                eeg_chunk_i, edf_chunk_i, eeg_status, edf_status, ...
                "match", "canonical_match", ...
                next_eeg_chunk_i, next_edf_chunk_i)];
        result.matched_chunk_count = result.matched_chunk_count + 1;
        if isnan(result.first_problem_chunk)
            result.initial_matched_chunk_count = ...
                result.initial_matched_chunk_count + 1;
        end
        eeg_chunk_i = next_eeg_chunk_i;
        edf_chunk_i = next_edf_chunk_i;
        continue
    end

    if xor(eeg_matches_canonical, edf_matches_canonical)
        if pair_matches
            error('match_triggers:StatusContradiction', ...
                ['Exactly one report marks EEG chunk %d / EDF chunk %d as ' ...
                 'canonical, but their complete interval sequences agree.'], ...
                eeg_chunk_i, edf_chunk_i)
        end

        if eeg_matches_canonical
            affected_system = "edf";
            affected_event_table = edf_event_table;
            affected_Fs = edf_Fs;
            affected_edges = edf_edges;
            affected_canonical_edges = edf_canonical_edges;
            affected_chunk_report = edf_chunk_report;
            affected_chunk_i = edf_chunk_i;
        else
            affected_system = "eeg";
            affected_event_table = eeg_event_table;
            affected_Fs = eeg_Fs;
            affected_edges = eeg_edges;
            affected_canonical_edges = eeg_canonical_edges;
            affected_chunk_report = eeg_chunk_report;
            affected_chunk_i = eeg_chunk_i;
        end

        [start_anchor_event_index, end_anchor_event_index, ...
            loss_prefix_count, loss_suffix_count] = ...
            locate_loss_anchors( ...
                affected_edges, affected_canonical_edges, ...
                interval_tolerance_sec);

        observed_trigger_count = ...
            affected_chunk_report.observed_trigger_count(affected_chunk_i);
        estimated_cycle_count = ...
            affected_chunk_report.estimated_cycle_count(affected_chunk_i);
        missing_boundary_diagnostic = ...
            affected_chunk_report.reason(affected_chunk_i) == ...
                "suspected_missing_boundary";
        canonical_trigger_count = height(affected_canonical_edges);

        if observed_trigger_count < canonical_trigger_count
            next_eeg_chunk_i = eeg_chunk_i + 1;
            next_edf_chunk_i = edf_chunk_i + 1;
            resolution_status = "resumed_same_offset";
            period_reason = "within_cycle_loss";
        elseif observed_trigger_count > canonical_trigger_count && ...
                missing_boundary_diagnostic && estimated_cycle_count == 2
            if affected_system == "eeg"
                next_eeg_chunk_i = eeg_chunk_i + 1;
                next_edf_chunk_i = edf_chunk_i + 2;
            else
                next_eeg_chunk_i = eeg_chunk_i + 2;
                next_edf_chunk_i = edf_chunk_i + 1;
            end
            resolution_status = "resumed_after_boundary_skip";
            period_reason = "suspected_missing_boundary";
        else
            next_eeg_chunk_i = NaN;
            next_edf_chunk_i = NaN;
            resolution_status = "unsupported_cycle_count_ambiguity";
            period_reason = "manual_cycle_count_review";
        end

        issue_outcome = affected_system + "_data_loss";
        result.suspected_missing_boundary = ...
            result.suspected_missing_boundary || missing_boundary_diagnostic;
        marker_period = empty_missing_period_table;
        marker_resolved = false;
        if has_amplifier_interruptions && affected_system == "eeg"
            [amplifier_interruptions, marker_period, ...
                marker_resolved] = resolve_generic_amplifier_loss( ...
                    amplifier_interruptions, ...
                    start_anchor_event_index, end_anchor_event_index, ...
                    loss_prefix_count, loss_suffix_count, ...
                    eeg_chunk_i, edf_chunk_i, ...
                    next_edf_chunk_i, resolution_status, ...
                    eeg_event_table, eeg_Fs, eeg_chunk_report, ...
                    edf_event_table, edf_Fs, edf_chunk_report, ...
                    edf_edges);
            result.amplifier_interruptions = amplifier_interruptions;
        end
        if marker_resolved
            result.missing_periods = [ ...
                result.missing_periods; marker_period];
        else
            result.missing_periods = [result.missing_periods; ...
                make_missing_period( ...
                affected_system, start_anchor_event_index, ...
                end_anchor_event_index, affected_event_table, affected_Fs, ...
                period_reason, eeg_chunk_i, edf_chunk_i)];
        end
        result = record_problem( ...
            result, eeg_chunk_i, edf_chunk_i, eeg_status, edf_status, ...
            issue_outcome, resolution_status, ...
            next_eeg_chunk_i, next_edf_chunk_i);

        if isnan(next_eeg_chunk_i)
            result.requires_relock = true;
            result.stopped_reason = "unsupported_cycle_count_ambiguity";
            break
        end

        result.requires_relock = any( ...
            isnan(result.missing_periods.end_anchor_event_index));
        eeg_chunk_i = next_eeg_chunk_i;
        edf_chunk_i = next_edf_chunk_i;
        continue
    end

    if pair_matches
        next_eeg_chunk_i = eeg_chunk_i + 1;
        next_edf_chunk_i = edf_chunk_i + 1;
        result = record_problem( ...
            result, eeg_chunk_i, edf_chunk_i, eeg_status, edf_status, ...
            "shared_trigger_glitch", "resumed_same_offset", ...
            next_eeg_chunk_i, next_edf_chunk_i);
        eeg_chunk_i = next_eeg_chunk_i;
        edf_chunk_i = next_edf_chunk_i;
        continue
    end

    eeg_prefix_count = matching_prefix_count( ...
        eeg_edges, eeg_canonical_edges, interval_tolerance_sec);
    edf_prefix_count = matching_prefix_count( ...
        edf_edges, edf_canonical_edges, interval_tolerance_sec);
    shared_prefix_count = min(eeg_prefix_count, edf_prefix_count);

    eeg_start_anchor = anchor_after_prefix(eeg_edges, shared_prefix_count);
    edf_start_anchor = anchor_after_prefix(edf_edges, shared_prefix_count);

    result.requires_relock = true;
    result.stopped_reason = "divergent_noncanonical_chunks";
    result.missing_periods = [result.missing_periods; ...
        make_missing_period( ...
            "eeg", eeg_start_anchor, NaN, eeg_event_table, eeg_Fs, ...
            "divergent_noncanonical_chunks", eeg_chunk_i, edf_chunk_i); ...
        make_missing_period( ...
            "edf", edf_start_anchor, NaN, edf_event_table, edf_Fs, ...
            "divergent_noncanonical_chunks", eeg_chunk_i, edf_chunk_i)];
    result = record_problem( ...
        result, eeg_chunk_i, edf_chunk_i, eeg_status, edf_status, ...
        "both_systems_unusable", "requires_next_shared_chunk", NaN, NaN);
    break
end

if ~result.terminal_chunk_handled && result.stopped_reason == "" && ...
        (eeg_chunk_i > height(eeg_chunk_report) || ...
         edf_chunk_i > height(edf_chunk_report))
    error('match_triggers:TerminalRegionSkipped', ...
        ['A chunk-index jump passed the terminal region before its start ' ...
         'could be aligned. Manual terminal review is required.'])
end

if result.terminal_chunk_handled && isnan(result.first_problem_chunk)
    result.outcome = "all_nonterminal_chunks_match";
    result.resolution_status = "terminal_anchor_identified";
end

eeg_input.event_table = eeg_event_table;
edf_input.event_table = edf_event_table;
result.amplifier_interruptions = amplifier_interruptions;
if has_amplifier_interruptions
    disp('HD-EEG amplifier interruption handling:')
    disp(amplifier_interruptions(:, { ...
        'interruption_id', 'gap_group_index', ...
        'resolution_status', 'exclude_from_segments', ...
        'eeg_start_anchor_event_index', 'eeg_end_anchor_event_index', ...
        'edf_start_anchor_event_index', 'edf_end_anchor_event_index'}))
end
if plot_alignment
    figure_handle = plot_trigger_alignment(result, eeg_input, edf_input);
end

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% END OF MATCH_TRIGGERS (MAIN FUNCTION)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
end

%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ADDITIONAL HELPER FUNCTIONS
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function validate_canonical_cycles( ...
    eeg_canonical_cycle, edf_canonical_cycle, interval_tolerance_sec)
%VALIDATE_CANONICAL_CYCLES Confirm that EEG and EDF cycles are equivalent.
%   VALIDATE_CANONICAL_CYCLES(EEG_CANONICAL_CYCLE, EDF_CANONICAL_CYCLE,
%   INTERVAL_TOLERANCE_SEC) requires both cycles to contain exactly 50
%   triggers with identical types and interval timing in the same order.

assert(istable(eeg_canonical_cycle) && istable(edf_canonical_cycle), ...
    'Canonical cycles must be tables.')
required_variables = ["type", "interval_to_next_sec"];
assert(all(ismember(required_variables, ...
    string(eeg_canonical_cycle.Properties.VariableNames))) && ...
    all(ismember(required_variables, ...
    string(edf_canonical_cycle.Properties.VariableNames))), ...
    'Canonical cycles must contain type and interval_to_next_sec variables.')
assert(isnumeric(interval_tolerance_sec) && ...
    isscalar(interval_tolerance_sec) && ...
    isfinite(interval_tolerance_sec) && interval_tolerance_sec >= 0, ...
    'interval_tolerance_sec must be a nonnegative finite scalar.')

expected_trigger_count = 50;
eeg_trigger_count = height(eeg_canonical_cycle);
edf_trigger_count = height(edf_canonical_cycle);
if eeg_trigger_count ~= expected_trigger_count || ...
        edf_trigger_count ~= expected_trigger_count
    error('validate_canonical_cycles:UnexpectedTriggerCount', ...
        ['Canonical cycles must each contain exactly %d triggers. ' ...
         'EEG contains %d and EDF contains %d.'], ...
        expected_trigger_count, eeg_trigger_count, edf_trigger_count)
end

eeg_type = strip(string(eeg_canonical_cycle.type(:)));
edf_type = strip(string(edf_canonical_cycle.type(:)));
assert(~any(ismissing(eeg_type)) && ~any(ismissing(edf_type)), ...
    'Canonical cycle trigger types must not contain missing values.')

type_mismatch_index = find(eeg_type ~= edf_type, 1, 'first');
if ~isempty(type_mismatch_index)
    error('validate_canonical_cycles:TriggerTypeMismatch', ...
        ['Canonical trigger types differ at row %d: ' ...
         'EEG is %s and EDF is %s.'], ...
        type_mismatch_index, eeg_type(type_mismatch_index), ...
        edf_type(type_mismatch_index))
end

assert(isnumeric(eeg_canonical_cycle.interval_to_next_sec) && ...
    isnumeric(edf_canonical_cycle.interval_to_next_sec), ...
    'Canonical cycle intervals must be numeric.')
eeg_interval_sec = double(eeg_canonical_cycle.interval_to_next_sec(:));
edf_interval_sec = double(edf_canonical_cycle.interval_to_next_sec(:));
assert(all(isfinite(eeg_interval_sec)) && all(isfinite(edf_interval_sec)), ...
    'Canonical cycle intervals must be finite.')

interval_error_sec = abs(eeg_interval_sec - edf_interval_sec);
comparison_scale = max([abs(eeg_interval_sec); abs(edf_interval_sec); 1]);
roundoff_tolerance_sec = 10 * eps(comparison_scale);
interval_mismatch_index = find( ...
    interval_error_sec > interval_tolerance_sec + roundoff_tolerance_sec, ...
    1, 'first');

if ~isempty(interval_mismatch_index)
    error('validate_canonical_cycles:IntervalMismatch', ...
        ['Canonical intervals differ at row %d by %.9g sec, exceeding ' ...
         'the %.9g sec tolerance.'], ...
        interval_mismatch_index, interval_error_sec(interval_mismatch_index), ...
        interval_tolerance_sec)
end

disp('EEG and EDF canonical cycles match.')

end

