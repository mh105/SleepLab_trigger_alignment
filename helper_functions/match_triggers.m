%%
function validate_system_inputs(eeg_input, edf_input)

assert(isstruct(eeg_input) && isscalar(eeg_input) && ...
    isstruct(edf_input) && isscalar(edf_input), ...
    'eeg_input and edf_input must be scalar structs.')
assert(all(isfield(eeg_input, {'event_table', 'Fs'})), ...
    'eeg_input must contain event_table and Fs fields.')
assert(all(isfield(edf_input, {'event_table', 'trigger_Fs'})), ...
    'edf_input must contain event_table and trigger_Fs fields.')
assert(istable(eeg_input.event_table) && istable(edf_input.event_table), ...
    'eeg_input.event_table and edf_input.event_table must be tables.')
assert(isnumeric(eeg_input.Fs) && isscalar(eeg_input.Fs) && ...
    isfinite(eeg_input.Fs) && eeg_input.Fs > 0 && ...
    isnumeric(edf_input.trigger_Fs) && isscalar(edf_input.trigger_Fs) && ...
    isfinite(edf_input.trigger_Fs) && edf_input.trigger_Fs > 0, ...
    'EEG Fs and EDF trigger_Fs must be positive finite scalars.')

end

