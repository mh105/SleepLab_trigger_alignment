%%
function validate_post_validation_restart( ...
    eeg_event_table, eeg_Fs, eeg_chunk_report, ...
    edf_event_table, edf_Fs, edf_chunk_report, tolerance_sec)

first_cycles_are_complete = ...
    eeg_chunk_report.status(1) == "match" && ...
    edf_chunk_report.status(1) == "match";
if first_cycles_are_complete
    eeg_edges = extract_chunk_edges( ...
        eeg_event_table, eeg_Fs, eeg_chunk_report, 1);
    edf_edges = extract_chunk_edges( ...
        edf_event_table, edf_Fs, edf_chunk_report, 1);
    first_cycles_are_complete = edges_match( ...
        eeg_edges, edf_edges, tolerance_sec);
end

if ~first_cycles_are_complete
    error('match_triggers:PostValidationCycleMismatch', ...
        ['The first complete EDF cycle after the final validation sequence ' ...
         'does not match HD-EEG cycle 1.'])
end

end

%%
function [result, eeg_anchor_event_index, edf_anchor_event_index] = ...
    resolve_partial_start( ...
        result, eeg_event_table, eeg_Fs, eeg_chunk_report, ...
        edf_event_table, edf_Fs, ...
        edf_chunk_report, edf_canonical_edges, tolerance_sec)

assert(height(edf_chunk_report) >= 2 && ...
    edf_chunk_report.status(1) == "partial_start", ...
    'match_triggers:InvalidPartialStart', ...
    'EDF partial start must precede an intact four-64 boundary.')
partial_event_index = ( ...
    edf_chunk_report.start_event_index(1): ...
    edf_chunk_report.end_event_index(1))';
if ~all(strip(string(edf_event_table.type(partial_event_index))) == "63")
    error('match_triggers:LateStartPrefixNotPure63', ...
        ['EDF triggers before the first intact four-64 boundary must all ' ...
         'be regular 63 triggers.'])
end

edf_partial_edges = extract_chunk_edges( ...
    edf_event_table, edf_Fs, edf_chunk_report, 1);
matching_interval_count = height(edf_partial_edges);
if matching_interval_count < 2
    error('match_triggers:LateStartInsufficientEvidence', ...
        ['At least two consecutive EDF intervals are required to establish ' ...
         'a partial-cycle initial alignment.'])
end

canonical_candidates = matching_sequence_starts( ...
    edf_partial_edges, edf_canonical_edges, tolerance_sec);
if isempty(canonical_candidates)
    error('match_triggers:LateStartCanonicalMismatch', ...
        ['The leading EDF intervals do not match a contiguous portion of ' ...
         'the canonical EDF cycle.'])
elseif numel(canonical_candidates) > 1
    error('match_triggers:LateStartAmbiguous', ...
        'The leading EDF intervals match multiple canonical cycle phases.')
end
canonical_start_interval = canonical_candidates(1);
if canonical_start_interval + matching_interval_count - 1 ~= ...
        height(edf_canonical_edges)
    error('match_triggers:LateStartNotCanonicalSuffix', ...
        ['The leading EDF intervals match the canonical cycle but do not ' ...
         'form its suffix through the next boundary.'])
end

if eeg_chunk_report.status(1) ~= "match"
    error('match_triggers:LateStartEegFirstCycleMismatch', ...
        'HD-EEG cycle 1 is not a complete canonical cycle.')
end
eeg_first_edges = extract_chunk_edges( ...
    eeg_event_table, eeg_Fs, eeg_chunk_report, 1);
eeg_candidates = matching_sequence_starts( ...
    edf_partial_edges, eeg_first_edges, tolerance_sec);
if isempty(eeg_candidates)
    error('match_triggers:LateStartEegFirstCycleMismatch', ...
        'The leading EDF intervals do not match HD-EEG cycle 1.')
elseif numel(eeg_candidates) > 1
    error('match_triggers:LateStartAmbiguous', ...
        'The leading EDF intervals match multiple phases in HD-EEG cycle 1.')
end
eeg_start_interval = eeg_candidates(1);
if eeg_start_interval ~= canonical_start_interval || ...
        eeg_start_interval + matching_interval_count - 1 ~= ...
            height(eeg_first_edges)
    error('match_triggers:LateStartPhaseDisagreement', ...
        ['Canonical EDF and actual HD-EEG cycle-1 evidence do not identify ' ...
         'the same suffix phase.'])
end

eeg_anchor_event_index = ...
    eeg_first_edges.source_event_index(eeg_start_interval);
edf_anchor_event_index = edf_partial_edges.source_event_index(1);
result.startup_mode = "partial_cycle_late_start";
result.initial_alignment_reason = "partial_cycle_late_start";
result.initial_cycle_offset_uncertain = true;
result.initial_canonical_interval_number = canonical_start_interval;
result.initial_matching_interval_count = matching_interval_count;
result.initial_matching_candidate_count = 1;
result.initial_matching_prefix_interval_count = 0;
result.initial_matching_suffix_interval_count = matching_interval_count;
result.comparison_history = [result.comparison_history; ...
    make_history_row( ...
        1, 1, eeg_chunk_report.status(1), edf_chunk_report.status(1), ...
        "partial_start_match", "initial_canonical_suffix_match", 2, 2)];

end

%%
function candidate_start = matching_sequence_starts( ...
    target_edges, reference_edges, tolerance_sec)

candidate_start = zeros(0, 1);
target_count = height(target_edges);
for start_i = 1:(height(reference_edges) - target_count + 1)
    comparison_edges = reference_edges( ...
        start_i:(start_i + target_count - 1), :);
    if edges_match(target_edges, comparison_edges, tolerance_sec)
        candidate_start(end + 1, 1) = start_i; %#ok<AGROW>
    end
end

end

%%
function [interruptions, has_interruptions] = ...
    initialize_amplifier_interruptions(eeg_input)

required_variables = [ ...
    "interruption_id", "pairing_status", ...
    "disconnect_raw_event_index", "disconnect_latency", ...
    "disconnect_event_text", ...
    "reconnect_raw_event_index", "reconnect_latency", ...
    "reconnect_event_text", ...
    "eeg_start_anchor_event_index", "eeg_start_anchor_latency", ...
    "eeg_end_anchor_event_index", "eeg_end_anchor_latency"];

if ~isfield(eeg_input, 'amplifier_interruptions')
    interruptions = table( ...
        zeros(0, 1), strings(0, 1), ...
        nan(0, 1), nan(0, 1), strings(0, 1), ...
        nan(0, 1), nan(0, 1), strings(0, 1), ...
        nan(0, 1), nan(0, 1), nan(0, 1), nan(0, 1), ...
        'VariableNames', cellstr(required_variables));
else
    interruptions = eeg_input.amplifier_interruptions;
    assert(istable(interruptions), ...
        'eeg_input.amplifier_interruptions must be a table.')
    assert(all(ismember(required_variables, ...
        string(interruptions.Properties.VariableNames))), ...
        ['eeg_input.amplifier_interruptions is missing one or more ' ...
         'required variables.'])
    assert(all(ismember(interruptions.pairing_status, ...
        ["paired"; "missing_reconnect"])), ...
        'Unsupported amplifier interruption pairing status.')
end

n_interruptions = height(interruptions);
interruptions.gap_group_index = zeros(n_interruptions, 1);
interruptions.resolution_status = ...
    repmat("not_reached", n_interruptions, 1);
interruptions.exclude_from_segments = false(n_interruptions, 1);
interruptions.edf_start_anchor_event_index = nan(n_interruptions, 1);
interruptions.edf_start_anchor_latency = nan(n_interruptions, 1);
interruptions.edf_end_anchor_event_index = nan(n_interruptions, 1);
interruptions.edf_end_anchor_latency = nan(n_interruptions, 1);

group_i = 0;
current_group_end = -Inf;
for interruption_i = 1:n_interruptions
    start_anchor = ...
        interruptions.eeg_start_anchor_event_index(interruption_i);
    end_anchor = ...
        interruptions.eeg_end_anchor_event_index(interruption_i);
    if isnan(start_anchor)
        interval_start = -Inf;
    else
        interval_start = start_anchor;
    end
    if interruptions.pairing_status(interruption_i) == ...
            "missing_reconnect" || isnan(end_anchor)
        interval_end = Inf;
    elseif isnan(start_anchor)
        interval_end = end_anchor;
    else
        interval_end = max(end_anchor, start_anchor + 1);
    end

    if group_i == 0 || interval_start > current_group_end
        group_i = group_i + 1;
        current_group_end = interval_end;
    else
        current_group_end = max(current_group_end, interval_end);
    end
    interruptions.gap_group_index(interruption_i) = group_i;
end

has_interruptions = n_interruptions > 0;

end

%%
function [result, interruptions, eeg_initial_anchor, ...
    edf_initial_anchor, eeg_event_table] = ...
    resolve_leading_amplifier_interruption( ...
        result, interruptions, eeg_initial_anchor, edf_initial_anchor, ...
        eeg_event_table, eeg_Fs, eeg_chunk_report, ...
        edf_event_table, edf_Fs, edf_chunk_report, edf_chunk_i, ...
        tolerance_sec)

leading_rows = find( ...
    isnan(interruptions.eeg_start_anchor_event_index) & ...
    interruptions.resolution_status == "not_reached");
if isempty(leading_rows)
    return
end

leading_groups = unique(interruptions.gap_group_index(leading_rows), ...
    'stable');
if numel(leading_groups) ~= 1
    error('match_triggers:MultipleLeadingAmplifierInterruptions', ...
        'Only one connected leading amplifier interruption is possible.')
end
group_rows = interruptions.gap_group_index == leading_groups;
end_anchor = max( ...
    interruptions.eeg_end_anchor_event_index(group_rows), [], 'omitnan');
if isempty(end_anchor) || isnan(end_anchor) || ...
        end_anchor >= height(eeg_event_table)
    error('match_triggers:UnanchoredLeadingAmplifierInterruption', ...
        ['A leading amplifier interruption has no complete post-reconnect ' ...
         'trigger interval. Initial alignment cannot be established.'])
end
if end_anchor <= eeg_initial_anchor
    interruptions.resolution_status(group_rows) = ...
        "before_initial_alignment";
    interruptions.exclude_from_segments(group_rows) = true;
    return
end
if end_anchor > eeg_chunk_report.end_event_index( ...
        result.initial_eeg_chunk_index)
    error('match_triggers:AmplifierCycleCountAmbiguity', ...
        ['A leading amplifier interruption reaches beyond the first ' ...
         'canonical cycle. Its EDF cycle placement is ambiguous.'])
end

event_offset = end_anchor - eeg_initial_anchor;
edf_end_anchor = edf_initial_anchor + event_offset;
if edf_end_anchor >= height(edf_event_table) || ...
        string(eeg_event_table.type(end_anchor)) ~= ...
        string(edf_event_table.type(edf_end_anchor))
    error('match_triggers:LeadingAmplifierRelockFailed', ...
        'The first post-reconnect trigger has no corresponding EDF anchor.')
end

eeg_edges = extract_chunk_edges( ...
    eeg_event_table, eeg_Fs, eeg_chunk_report, ...
    result.initial_eeg_chunk_index);
edf_edges = extract_chunk_edges( ...
    edf_event_table, edf_Fs, edf_chunk_report, edf_chunk_i);
eeg_confirm_i = find( ...
    eeg_edges.source_event_index == end_anchor, 1);
edf_confirm_i = find( ...
    edf_edges.source_event_index == edf_end_anchor, 1);
if isempty(eeg_confirm_i) || isempty(edf_confirm_i) || ...
        ~single_edge_matches( ...
            eeg_edges, eeg_confirm_i, edf_edges, edf_confirm_i, ...
            tolerance_sec)
    error('match_triggers:LeadingAmplifierRelockFailed', ...
        ['The first full post-reconnect trigger interval does not match ' ...
         'the corresponding EDF interval.'])
end

for interruption_i = find(group_rows)'
    interruptions.resolution_status(interruption_i) = ...
        "leading_relocked";
    interruptions.exclude_from_segments(interruption_i) = true;
    row_end_anchor = ...
        interruptions.eeg_end_anchor_event_index(interruption_i);
    if isfinite(row_end_anchor) && row_end_anchor > eeg_initial_anchor
        row_offset = row_end_anchor - eeg_initial_anchor;
        row_edf_end_anchor = edf_initial_anchor + row_offset;
        interruptions.edf_end_anchor_event_index(interruption_i) = ...
            row_edf_end_anchor;
        interruptions.edf_end_anchor_latency(interruption_i) = ...
            double(edf_event_table.latency(row_edf_end_anchor));
    end
end

eeg_initial_anchor = end_anchor;
edf_initial_anchor = edf_end_anchor;
eeg_event_table.is_pre_alignment(1:end_anchor - 1) = true;
result.initial_alignment_reason = "amplifier_reconnect";

end

%%
function interruptions = resolve_skipped_partial_start_interruptions( ...
    interruptions, eeg_initial_anchor, eeg_chunk_report, n_eeg_events)

unresolved_groups = unique(interruptions.gap_group_index( ...
    interruptions.resolution_status == "not_reached"), 'stable');
partial_chunk_end = eeg_chunk_report.end_event_index(1);

for group_i = unresolved_groups'
    group_rows = interruptions.gap_group_index == group_i;
    [start_anchor, end_anchor, is_leading] = amplifier_group_bounds( ...
        interruptions, group_i, n_eeg_events);
    if ~is_leading && isfinite(end_anchor) && ...
            end_anchor <= eeg_initial_anchor
        interruptions.resolution_status(group_rows) = ...
            "before_initial_alignment";
        interruptions.exclude_from_segments(group_rows) = true;
    elseif is_leading || ~isfinite(start_anchor) || ...
            start_anchor <= partial_chunk_end
        error('match_triggers:PartialStartAmplifierInterruption', ...
            ['An unresolved HD-EEG amplifier interruption overlaps the ' ...
             'matched partial first cycle. Its alignment cannot be ' ...
             'established automatically.'])
    end
end

end

%%
function [terminal_group_ids, interruptions] = ...
    terminal_amplifier_groups( ...
        interruptions, eeg_chunk_report, eeg_chunk_i, n_eeg_events)

terminal_group_ids = zeros(0, 1);
unresolved_groups = unique(interruptions.gap_group_index( ...
    interruptions.resolution_status == "not_reached"), 'stable');
chunk_start = eeg_chunk_report.start_event_index(eeg_chunk_i);
chunk_end = eeg_chunk_report.end_event_index(eeg_chunk_i);

for group_i = unresolved_groups'
    [start_anchor, end_anchor, is_leading, is_terminal] = ...
        amplifier_group_bounds(interruptions, group_i, n_eeg_events);
    if is_leading && is_terminal
        error('match_triggers:UnanchoredLeadingAmplifierInterruption', ...
            ['The EEG recording begins inside an amplifier interruption ' ...
             'and never establishes a post-reconnect interval.'])
    end
    if is_terminal && isfinite(start_anchor) && ...
            start_anchor >= chunk_start && start_anchor <= chunk_end
        terminal_group_ids(end + 1, 1) = group_i; %#ok<AGROW>
    elseif isfinite(end_anchor) && end_anchor < start_anchor
        error('match_triggers:InvalidAmplifierAnchors', ...
            'Amplifier interruption anchors occur out of order.')
    end
end

end

%%
function [result, eeg_event_table, edf_event_table, interruptions] = ...
    align_terminal_amplifier_loss( ...
        result, group_ids, interruptions, eeg_chunk_i, edf_chunk_i, ...
        eeg_event_table, eeg_Fs, eeg_chunk_report, ...
        edf_event_table, edf_Fs, edf_chunk_report, tolerance_sec)

start_anchor = Inf;
for group_i = group_ids'
    [group_start, ~] = amplifier_group_bounds( ...
        interruptions, group_i, height(eeg_event_table));
    start_anchor = min(start_anchor, group_start);
end

eeg_chunk_start = eeg_chunk_report.start_event_index(eeg_chunk_i);
edf_chunk_start = edf_chunk_report.start_event_index(edf_chunk_i);
event_offset = start_anchor - eeg_chunk_start;
edf_start_anchor = edf_chunk_start + event_offset;
if edf_start_anchor > height(edf_event_table) || ...
        string(eeg_event_table.type(start_anchor)) ~= ...
        string(edf_event_table.type(edf_start_anchor))
    error('match_triggers:TerminalAmplifierAnchorMismatch', ...
        'The last pre-disconnect EEG trigger has no corresponding EDF trigger.')
end

eeg_edges = extract_chunk_edges( ...
    eeg_event_table, eeg_Fs, eeg_chunk_report, eeg_chunk_i);
edf_edges = extract_chunk_edges( ...
    edf_event_table, edf_Fs, edf_chunk_report, edf_chunk_i);
prefix_edge_count = find( ...
    eeg_edges.source_event_index == start_anchor, 1) - 1;
if isempty(prefix_edge_count) || height(eeg_edges) ~= height(edf_edges)
    error('match_triggers:TerminalAmplifierAnchorMismatch', ...
        'The terminal amplifier interruption cannot be mapped to EDF safely.')
end
for edge_i = 1:prefix_edge_count
    if ~single_edge_matches( ...
            eeg_edges, edge_i, edf_edges, edge_i, tolerance_sec)
        error('match_triggers:TerminalAmplifierAnchorMismatch', ...
            ['EEG and EDF differ before the terminal amplifier ' ...
             'disconnect anchor.'])
    end
end

for group_i = group_ids'
    group_rows = interruptions.gap_group_index == group_i;
    for interruption_i = find(group_rows)'
        interruptions.resolution_status(interruption_i) = ...
            "terminal_eeg_loss";
        interruptions.exclude_from_segments(interruption_i) = true;
        row_start = ...
            interruptions.eeg_start_anchor_event_index(interruption_i);
        row_offset = row_start - eeg_chunk_start;
        row_edf_start = edf_chunk_start + row_offset;
        interruptions.edf_start_anchor_event_index(interruption_i) = ...
            row_edf_start;
        interruptions.edf_start_anchor_latency(interruption_i) = ...
            double(edf_event_table.latency(row_edf_start));
    end
end

result.missing_periods = [result.missing_periods; ...
    make_missing_period( ...
        "eeg", start_anchor, NaN, eeg_event_table, eeg_Fs, ...
        "amplifier_disconnect", eeg_chunk_i, edf_chunk_i)];
result = record_problem( ...
    result, eeg_chunk_i, edf_chunk_i, ...
    eeg_chunk_report.status(eeg_chunk_i), ...
    edf_chunk_report.status(edf_chunk_i), ...
    "eeg_data_loss", "terminal_eeg_loss", NaN, NaN);

eeg_event_table.is_terminal(start_anchor:end) = true;
edf_event_table.is_terminal(edf_start_anchor:end) = true;
eeg_event_table.is_terminal_alignment_anchor(start_anchor) = true;
edf_event_table.is_terminal_alignment_anchor(edf_start_anchor) = true;
result.terminal_chunk_handled = true;
result.terminal_chunk_deferred = true;
result.terminal_relation = "eeg_shorter";
result.terminal_later_action = "zero_pad_eeg";
result.eeg_zero_padding_required = true;
result.eeg_terminal_chunk_indices = ...
    eeg_chunk_i:height(eeg_chunk_report);
result.edf_terminal_chunk_indices = ...
    edf_chunk_i:height(edf_chunk_report);
result.eeg_terminal_anchor_event_index = start_anchor;
result.edf_terminal_anchor_event_index = edf_start_anchor;
result.eeg_terminal_anchor_latency = ...
    double(eeg_event_table.latency(start_anchor));
result.edf_terminal_anchor_latency = ...
    double(edf_event_table.latency(edf_start_anchor));
result.terminal_common_trigger_count = event_offset + 1;
result.requires_relock = false;
result.stopped_reason = "terminal_region_identified";

end

%%
function [result, interruptions, action] = ...
    resolve_amplifier_interruptions_in_chunk( ...
        result, interruptions, eeg_chunk_i, edf_chunk_i, ...
        eeg_event_table, eeg_Fs, eeg_chunk_report, eeg_edges, ...
        edf_event_table, edf_chunk_report, edf_edges, ...
        eeg_status, edf_status, tolerance_sec)

action = "none";
chunk_start = eeg_chunk_report.start_event_index(eeg_chunk_i);
chunk_end = eeg_chunk_report.end_event_index(eeg_chunk_i);
candidate_rows = ...
    (interruptions.resolution_status == "not_reached" & ...
     isfinite(interruptions.eeg_start_anchor_event_index) & ...
     interruptions.eeg_start_anchor_event_index >= chunk_start & ...
     interruptions.eeg_start_anchor_event_index <= chunk_end) | ...
    (eeg_chunk_i == 1 & ...
     interruptions.resolution_status == "leading_relocked") | ...
    (interruptions.resolution_status == "excluded_and_relocked" & ...
     isfinite(interruptions.eeg_start_anchor_event_index) & ...
     isfinite(interruptions.eeg_end_anchor_event_index) & ...
     interruptions.eeg_start_anchor_event_index < chunk_start & ...
     interruptions.eeg_end_anchor_event_index >= chunk_start);
group_ids = unique( ...
    interruptions.gap_group_index(candidate_rows), 'stable');
if isempty(group_ids)
    return
end

all_group_rows = ismember(interruptions.gap_group_index, group_ids);
group_end = max( ...
    interruptions.eeg_end_anchor_event_index(all_group_rows), [], ...
    'omitnan');
if isempty(group_end) || isnan(group_end) || ...
        ~any(edf_status == ["match", "partial_end"])
    interruptions.resolution_status(all_group_rows) = "manual_review";
    return
end
for group_i = group_ids'
    group_rows = interruptions.gap_group_index == group_i;
    if all(interruptions.resolution_status(group_rows) ~= "not_reached")
        continue
    end
    [group_start_anchor, group_end_anchor] = amplifier_group_bounds( ...
        interruptions, group_i, height(eeg_event_table));
    if isfinite(group_start_anchor) && isfinite(group_end_anchor) && ...
            group_end_anchor - group_start_anchor >= height(edf_edges)
        interruptions.resolution_status(all_group_rows) = "manual_review";
        result.missing_periods = [result.missing_periods; ...
            make_missing_period( ...
                "eeg", group_start_anchor, group_end_anchor, ...
                eeg_event_table, eeg_Fs, "manual_cycle_count_review", ...
                eeg_chunk_i, edf_chunk_i)];
        result = record_problem( ...
            result, eeg_chunk_i, edf_chunk_i, eeg_status, edf_status, ...
            "eeg_data_loss", "unsupported_cycle_count_ambiguity", ...
            NaN, NaN);
        result.requires_relock = true;
        result.stopped_reason = "unsupported_cycle_count_ambiguity";
        action = "stop";
        return
    end
end
if height(eeg_edges) ~= height(edf_edges) || ...
        ~isequal(eeg_edges.source_type, edf_edges.source_type) || ...
        ~isequal(eeg_edges.destination_type, edf_edges.destination_type)
    return
end

n_edges = height(eeg_edges);
edge_matches = false(n_edges, 1);
for edge_i = 1:n_edges
    edge_matches(edge_i) = single_edge_matches( ...
        eeg_edges, edge_i, edf_edges, edge_i, tolerance_sec);
end

marked_edge = false(n_edges, 1);
group_masks = cell(numel(group_ids), 1);
for group_offset = 1:numel(group_ids)
    group_i = group_ids(group_offset);
    group_rows = find(interruptions.gap_group_index == group_i);
    group_mask = false(n_edges, 1);
    for interruption_i = group_rows'
        start_anchor = ...
            interruptions.eeg_start_anchor_event_index(interruption_i);
        end_anchor = ...
            interruptions.eeg_end_anchor_event_index(interruption_i);
        if isnan(start_anchor)
            row_mask = ...
                eeg_edges.source_event_index < end_anchor;
        elseif end_anchor > start_anchor
            row_mask = ...
                eeg_edges.source_event_index >= start_anchor & ...
                eeg_edges.source_event_index < end_anchor;
        else
            row_mask = eeg_edges.source_event_index == start_anchor;
        end
        group_mask = group_mask | row_mask;
    end
    group_masks{group_offset} = group_mask;
    marked_edge = marked_edge | group_mask;
end

outside_mismatch = any(~edge_matches & ~marked_edge);
eeg_longer_mismatch = any( ...
    marked_edge & ~edge_matches & ...
    eeg_edges.interval_sec > edf_edges.interval_sec + tolerance_sec);
if outside_mismatch || eeg_longer_mismatch
    interruptions.resolution_status(all_group_rows) = "manual_review";
    return
end

excluded_group = false(numel(group_ids), 1);
for group_offset = 1:numel(group_ids)
    group_i = group_ids(group_offset);
    group_rows = interruptions.gap_group_index == group_i;
    group_mask = group_masks{group_offset};
    is_leading_group = all(isnan( ...
        interruptions.eeg_start_anchor_event_index(group_rows)));
    was_excluded = all(interruptions.resolution_status(group_rows) == ...
        "excluded_and_relocked");
    [group_start_anchor, group_end_anchor] = amplifier_group_bounds( ...
        interruptions, group_i, height(eeg_event_table));
    is_single_interval = isfinite(group_start_anchor) && ...
        isfinite(group_end_anchor) && ...
        group_end_anchor - group_start_anchor == 1;
    retained = ~was_excluded && ~is_leading_group && ...
        is_single_interval && ...
        all(edge_matches(group_mask));

    for interruption_i = find(group_rows)'
        start_anchor = ...
            interruptions.eeg_start_anchor_event_index(interruption_i);
        end_anchor = ...
            interruptions.eeg_end_anchor_event_index(interruption_i);
        [edf_end_anchor, end_anchor_mapped] = ...
            map_eeg_anchor_to_edf( ...
                end_anchor, eeg_chunk_i, edf_chunk_i, ...
                eeg_event_table, eeg_chunk_report, ...
                edf_event_table, edf_chunk_report);
        if ~end_anchor_mapped
            interruptions.resolution_status(all_group_rows) = ...
                "manual_review";
            action = "stop";
            result.requires_relock = true;
            result.stopped_reason = ...
                "unsupported_cycle_count_ambiguity";
            return
        end
        if isfinite(start_anchor)
            [edf_start_anchor, start_anchor_mapped] = ...
                map_eeg_anchor_to_edf( ...
                    start_anchor, eeg_chunk_i, edf_chunk_i, ...
                    eeg_event_table, eeg_chunk_report, ...
                    edf_event_table, edf_chunk_report);
            if ~start_anchor_mapped
                interruptions.resolution_status(all_group_rows) = ...
                    "manual_review";
                action = "stop";
                result.requires_relock = true;
                result.stopped_reason = ...
                    "unsupported_cycle_count_ambiguity";
                return
            end
            interruptions.edf_start_anchor_event_index(interruption_i) = ...
                edf_start_anchor;
            interruptions.edf_start_anchor_latency(interruption_i) = ...
                double(edf_event_table.latency(edf_start_anchor));
        end
        interruptions.edf_end_anchor_event_index(interruption_i) = ...
            edf_end_anchor;
        interruptions.edf_end_anchor_latency(interruption_i) = ...
            double(edf_event_table.latency(edf_end_anchor));
        if was_excluded
            interruptions.resolution_status(interruption_i) = ...
                "excluded_and_relocked";
            interruptions.exclude_from_segments(interruption_i) = true;
        elseif is_leading_group
            interruptions.resolution_status(interruption_i) = ...
                "leading_relocked";
            interruptions.exclude_from_segments(interruption_i) = true;
        elseif retained
            interruptions.resolution_status(interruption_i) = ...
                "retained_within_tolerance";
        else
            interruptions.resolution_status(interruption_i) = ...
                "excluded_and_relocked";
            interruptions.exclude_from_segments(interruption_i) = true;
        end
    end

    if ~retained
        excluded_group(group_offset) = true;
        if ~is_leading_group && ~was_excluded
            [start_anchor, end_anchor] = amplifier_group_bounds( ...
                interruptions, group_i, height(eeg_event_table));
            result.missing_periods = [result.missing_periods; ...
                make_missing_period( ...
                    "eeg", start_anchor, end_anchor, ...
                    eeg_event_table, eeg_Fs, "amplifier_disconnect", ...
                    eeg_chunk_i, edf_chunk_i)];
        end
    end
end

if any(excluded_group)
    result = record_problem( ...
        result, eeg_chunk_i, edf_chunk_i, eeg_status, edf_status, ...
        "eeg_data_loss", "resumed_same_offset", ...
        eeg_chunk_i + 1, edf_chunk_i + 1);
    result.requires_relock = false;
    action = "advance";
end

end

%%
function [edf_anchor, mapped] = map_eeg_anchor_to_edf( ...
    eeg_anchor, current_eeg_chunk_i, current_edf_chunk_i, ...
    eeg_event_table, eeg_chunk_report, edf_event_table, edf_chunk_report)

if isnan(eeg_anchor)
    edf_anchor = NaN;
    mapped = true;
    return
end

eeg_anchor_chunk_i = find( ...
    eeg_chunk_report.start_event_index <= eeg_anchor & ...
    eeg_chunk_report.end_event_index >= eeg_anchor, 1, 'first');
if isempty(eeg_anchor_chunk_i)
    edf_anchor = NaN;
    mapped = false;
    return
end

edf_anchor_chunk_i = current_edf_chunk_i + ...
    (eeg_anchor_chunk_i - current_eeg_chunk_i);
if edf_anchor_chunk_i < 1 || ...
        edf_anchor_chunk_i > height(edf_chunk_report)
    edf_anchor = NaN;
    mapped = false;
    return
end

event_offset = eeg_anchor - ...
    eeg_chunk_report.start_event_index(eeg_anchor_chunk_i);
edf_anchor = ...
    edf_chunk_report.start_event_index(edf_anchor_chunk_i) + event_offset;
mapped = edf_anchor <= edf_chunk_report.end_event_index(edf_anchor_chunk_i) && ...
    string(eeg_event_table.type(eeg_anchor)) == ...
        string(edf_event_table.type(edf_anchor));
if ~mapped
    edf_anchor = NaN;
end

end

%%
function [interruptions, missing_period, resolved] = ...
    resolve_generic_amplifier_loss( ...
        interruptions, inferred_start_anchor, inferred_end_anchor, ...
        prefix_count, suffix_count, eeg_chunk_i, edf_chunk_i, ...
        next_edf_chunk_i, resolution_status, ...
        eeg_event_table, eeg_Fs, eeg_chunk_report, ...
        edf_event_table, edf_Fs, edf_chunk_report, edf_edges)

missing_period = empty_missing_period_table;
resolved = false;
chunk_start = eeg_chunk_report.start_event_index(eeg_chunk_i);
chunk_end = eeg_chunk_report.end_event_index(eeg_chunk_i);
candidate_rows = ...
    interruptions.resolution_status == "not_reached" & ...
    isfinite(interruptions.eeg_start_anchor_event_index) & ...
    interruptions.eeg_start_anchor_event_index >= chunk_start & ...
    interruptions.eeg_start_anchor_event_index <= chunk_end;
group_ids = unique( ...
    interruptions.gap_group_index(candidate_rows), 'stable');
if isempty(group_ids)
    return
end

all_group_rows = ismember(interruptions.gap_group_index, group_ids);
if numel(group_ids) ~= 1 || ...
        resolution_status == "unsupported_cycle_count_ambiguity" || ...
        ~isfinite(next_edf_chunk_i) || suffix_count == 0
    interruptions.resolution_status(all_group_rows) = "manual_review";
    return
end

group_i = group_ids(1);
[start_anchor, end_anchor] = amplifier_group_bounds( ...
    interruptions, group_i, height(eeg_event_table));
if start_anchor ~= inferred_start_anchor || ...
        end_anchor ~= inferred_end_anchor
    interruptions.resolution_status(all_group_rows) = "manual_review";
    return
end

edf_start_anchor = anchor_after_prefix(edf_edges, prefix_count);
clean_suffix_chunk_i = next_edf_chunk_i - 1;
if clean_suffix_chunk_i < 1 || ...
        clean_suffix_chunk_i > height(edf_chunk_report)
    interruptions.resolution_status(all_group_rows) = "manual_review";
    return
end
clean_suffix_edges = extract_chunk_edges( ...
    edf_event_table, edf_Fs, edf_chunk_report, clean_suffix_chunk_i);
first_suffix_edge = height(clean_suffix_edges) - suffix_count + 1;
if first_suffix_edge < 1
    interruptions.resolution_status(all_group_rows) = "manual_review";
    return
end
edf_end_anchor = ...
    clean_suffix_edges.source_event_index(first_suffix_edge);

for interruption_i = find(all_group_rows)'
    interruptions.resolution_status(interruption_i) = ...
        "excluded_and_relocked";
    interruptions.exclude_from_segments(interruption_i) = true;
    interruptions.edf_start_anchor_event_index(interruption_i) = ...
        edf_start_anchor;
    interruptions.edf_start_anchor_latency(interruption_i) = ...
        double(edf_event_table.latency(edf_start_anchor));
    interruptions.edf_end_anchor_event_index(interruption_i) = ...
        edf_end_anchor;
    interruptions.edf_end_anchor_latency(interruption_i) = ...
        double(edf_event_table.latency(edf_end_anchor));
end

missing_period = make_missing_period( ...
    "eeg", start_anchor, end_anchor, eeg_event_table, eeg_Fs, ...
    "amplifier_disconnect", eeg_chunk_i, edf_chunk_i);
resolved = true;

end

%%
function [start_anchor, end_anchor, is_leading, is_terminal] = ...
    amplifier_group_bounds(interruptions, group_i, n_eeg_events)

group_rows = interruptions.gap_group_index == group_i;
start_values = interruptions.eeg_start_anchor_event_index(group_rows);
end_values = interruptions.eeg_end_anchor_event_index(group_rows);
start_anchor = min(start_values, [], 'omitnan');
end_anchor = max(end_values, [], 'omitnan');
is_leading = all(isnan(start_values));
is_terminal = any( ...
    interruptions.pairing_status(group_rows) == "missing_reconnect") || ...
    all(isnan(end_values));

if isempty(start_anchor)
    start_anchor = NaN;
end
if isempty(end_anchor)
    end_anchor = NaN;
end
if ~is_terminal && isfinite(end_anchor) && end_anchor >= n_eeg_events
    is_terminal = true;
end
if ~is_leading && isfinite(start_anchor) && isfinite(end_anchor) && ...
        end_anchor <= start_anchor
    end_anchor = start_anchor + 1;
end

end

%%
function [result, edf_chunk_i, edf_event_table] = ...
    resolve_initial_alignment( ...
        result, eeg_event_table, eeg_Fs, eeg_chunk_report, ...
        edf_event_table, edf_Fs, edf_canonical_edges, edf_chunk_report, ...
        tolerance_sec)

% T1...T50 label trigger positions within a cycle, not chunk numbers.
edf_chunk_i = 1;
if ~eeg_chunk_report.has_next_boundary(1) || ...
        ~edf_chunk_report.has_next_boundary(1)
    return
end

eeg_first_edges = extract_chunk_edges( ...
    eeg_event_table, eeg_Fs, eeg_chunk_report, 1);
edf_first_edges = extract_chunk_edges( ...
    edf_event_table, edf_Fs, edf_chunk_report, 1);
if edges_match(eeg_first_edges, edf_first_edges, tolerance_sec)
    return
end
if eeg_chunk_report.status(1) ~= "match"
    return
end

if edf_chunk_report.status(1) == "match"
    return
end

edf_first_trigger_count = edf_chunk_report.observed_trigger_count(1);
canonical_trigger_count = height(edf_canonical_edges);
if edf_first_trigger_count > canonical_trigger_count && ...
        edf_chunk_report.reason(1) == "suspected_missing_boundary" && ...
        edf_chunk_report.estimated_cycle_count(1) == 2
    % Missing boundary -- EDF chunk 1 contains parts of two EEG cycles.
    % EEG: [T1 ........ T50] [T1 ........ T50] [T1 ...]
    % EDF: [T1 ........ T50      T7 .... T50] [T1 ...]
    % Keep EEG1 <-> EDF1; the main loop skips the consumed EEG cycle.
    result.initial_alignment_reason = ...
        "edf_first_chunk_missing_boundary";
    result.initial_cycle_offset_uncertain = true;
    return
elseif edf_first_trigger_count >= canonical_trigger_count
    return
end

result.initial_cycle_offset_uncertain = true;

[~, ~, matching_prefix_count, matching_suffix_count] = ...
    locate_loss_anchors( ...
        edf_first_edges, edf_canonical_edges, tolerance_sec);
result.initial_matching_prefix_interval_count = matching_prefix_count;
result.initial_matching_suffix_interval_count = matching_suffix_count;
% Data loss within one cycle -- retain EEG1 <-> EDF1.
% EEG1: T1 T2 ... Tk  T(k+1) ...... T(m-1)  Tm ... T50
% EDF1: T1 T2 ... Tk  |------ missing ------|  Tm ... T50
%        matching prefix                         matching suffix
if matching_prefix_count > 0 && matching_suffix_count > 0
    result.initial_alignment_reason = "edf_first_chunk_bracketed_loss";
    return
end

% Trigger-box/HD-EEG restart -- shift EEG1 to a later EDF chunk.
% EEG1:                                T1 T2 ........ T50
% EDF1: T1 ... old/incomplete fragment | restart |
% EDFk:                                T1 T2 ........ T50
%                                      ^ new shared four-64 boundary
% Mark EDF events before EDFk as pre-alignment; start EEG1 <-> EDFk.
for candidate_chunk_i = 2:height(edf_chunk_report)
    if ~edf_chunk_report.has_next_boundary(candidate_chunk_i) || ...
            edf_chunk_report.status(candidate_chunk_i) ~= "match"
        continue
    end

    edf_candidate_edges = extract_chunk_edges( ...
        edf_event_table, edf_Fs, edf_chunk_report, candidate_chunk_i);
    if ~edges_match(eeg_first_edges, edf_candidate_edges, tolerance_sec)
        continue
    end

    % A bounded canonical candidate restarts at T1, the four-64 boundary.
    candidate_start_event_index = ...
        edf_chunk_report.start_event_index(candidate_chunk_i);
    edf_event_table.is_pre_alignment( ...
        1:candidate_start_event_index - 1) = true;
    edf_chunk_i = candidate_chunk_i;
    result.initial_edf_chunk_index = candidate_chunk_i;
    result.edf_leading_restart_inferred = true;
    result.edf_pre_alignment_event_count = ...
        candidate_start_event_index - 1;
    result.initial_alignment_reason = ...
        "edf_restart_at_t1_boundary";
    return
end

end

