assert(istable(eeg_chunk_report) && istable(edf_chunk_report), ...
    'Chunk reports must be tables.')
required_report_variables = [ ...
    "start_event_index", "end_event_index", "observed_trigger_count", ...
    "has_next_boundary", "estimated_cycle_count", "status", "reason"];
assert(all(ismember(required_report_variables, ...
    string(eeg_chunk_report.Properties.VariableNames))) && ...
    all(ismember(required_report_variables, ...
    string(edf_chunk_report.Properties.VariableNames))), ...
    'Chunk reports are missing variables required for trigger matching.')

end
