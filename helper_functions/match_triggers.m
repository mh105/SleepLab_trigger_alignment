%%
function edges = extract_chunk_edges(event_table, Fs, chunk_report, chunk_i)

start_event_index = chunk_report.start_event_index(chunk_i);
end_event_index = chunk_report.end_event_index(chunk_i);
event_index = (start_event_index:end_event_index)';

if chunk_report.has_next_boundary(chunk_i)
    assert(chunk_i < height(chunk_report), ...
        'A bounded chunk must have a following chunk boundary.')
    next_boundary_index = chunk_report.start_event_index(chunk_i + 1);
    source_event_index = event_index;
    destination_event_index = [event_index(2:end); next_boundary_index];
else
    source_event_index = event_index(1:end - 1);
    destination_event_index = event_index(2:end);
end

source_type = strip(string(event_table.type(source_event_index)));
destination_type = strip(string(event_table.type(destination_event_index)));
interval_sec = ( ...
    double(event_table.latency(destination_event_index)) - ...
    double(event_table.latency(source_event_index))) ./ Fs;

edges = table( ...
    source_type, destination_type, interval_sec, ...
    source_event_index, destination_event_index);

end

%%
function edges = extract_canonical_edges(canonical_cycle)

n_triggers = height(canonical_cycle);
source_event_index = (1:n_triggers)';
destination_event_index = [source_event_index(2:end); 1];
source_type = strip(string(canonical_cycle.type));
destination_type = source_type(destination_event_index);
interval_sec = double(canonical_cycle.interval_to_next_sec(:));

edges = table( ...
    source_type, destination_type, interval_sec, ...
    source_event_index, destination_event_index);

end

%%
function is_match = edges_match(first_edges, second_edges, tolerance_sec)

if height(first_edges) ~= height(second_edges) || ...
        ~isequal(first_edges.source_type, second_edges.source_type) || ...
        ~isequal(first_edges.destination_type, second_edges.destination_type)
    is_match = false;
    return
end

interval_error_sec = abs( ...
    first_edges.interval_sec - second_edges.interval_sec);
comparison_scale = max([ ...
    abs(first_edges.interval_sec); abs(second_edges.interval_sec); 1]);
roundoff_tolerance_sec = 10 * eps(comparison_scale);
is_match = all( ...
    interval_error_sec <= tolerance_sec + roundoff_tolerance_sec);

end

%%
function [start_anchor_event_index, end_anchor_event_index, ...
    prefix_count, suffix_count] = ...
    locate_loss_anchors(observed_edges, canonical_edges, tolerance_sec)

prefix_count = matching_prefix_count( ...
    observed_edges, canonical_edges, tolerance_sec);
start_anchor_event_index = anchor_after_prefix( ...
    observed_edges, prefix_count);

suffix_count = 0;
observed_i = height(observed_edges);
canonical_i = height(canonical_edges);
while observed_i > prefix_count && canonical_i >= 1 && ...
        single_edge_matches( ...
            observed_edges, observed_i, ...
            canonical_edges, canonical_i, tolerance_sec)
    suffix_count = suffix_count + 1;
    observed_i = observed_i - 1;
    canonical_i = canonical_i - 1;
end

if suffix_count == 0
    end_anchor_event_index = NaN;
else
    first_suffix_edge = height(observed_edges) - suffix_count + 1;
    end_anchor_event_index = ...
        observed_edges.source_event_index(first_suffix_edge);
    if end_anchor_event_index <= start_anchor_event_index
        error('match_triggers:OverlappingAnchors', ...
            'The inferred loss anchors overlap or occur out of order.')
    end
end

end

%%
function prefix_count = matching_prefix_count( ...
    observed_edges, canonical_edges, tolerance_sec)

prefix_count = 0;
max_prefix_count = min(height(observed_edges), height(canonical_edges));
while prefix_count < max_prefix_count && ...
        single_edge_matches( ...
            observed_edges, prefix_count + 1, ...
            canonical_edges, prefix_count + 1, tolerance_sec)
    prefix_count = prefix_count + 1;
end

end

%%
function event_index = anchor_after_prefix(edges, prefix_count)

assert(~isempty(edges), ...
    'A discrepant chunk must contain at least one trigger interval.')
if prefix_count < height(edges)
    event_index = edges.source_event_index(prefix_count + 1);
else
    event_index = edges.destination_event_index(end);
end

end

%%
function is_match = single_edge_matches( ...
    first_edges, first_i, second_edges, second_i, tolerance_sec)

types_match = ...
    first_edges.source_type(first_i) == second_edges.source_type(second_i) && ...
    first_edges.destination_type(first_i) == ...
        second_edges.destination_type(second_i);
comparison_scale = max([ ...
    abs(first_edges.interval_sec(first_i)), ...
    abs(second_edges.interval_sec(second_i)), 1]);
roundoff_tolerance_sec = 10 * eps(comparison_scale);
interval_matches = abs( ...
    first_edges.interval_sec(first_i) - ...
    second_edges.interval_sec(second_i)) <= ...
    tolerance_sec + roundoff_tolerance_sec;
is_match = types_match && interval_matches;

end

%%
function missing_period = make_missing_period( ...
    system, start_event_index, end_event_index, event_table, Fs, reason, ...
    eeg_chunk_i, edf_chunk_i)

start_latency = double(event_table.latency(start_event_index));
start_time_sec = (start_latency - 1) ./ Fs;

if isnan(end_event_index)
    end_latency = NaN;
    end_time_sec = NaN;
else
    end_latency = double(event_table.latency(end_event_index));
    end_time_sec = (end_latency - 1) ./ Fs;
end

missing_period = table( ...
    system, eeg_chunk_i, edf_chunk_i, start_event_index, end_event_index, ...
    start_latency, end_latency, start_time_sec, end_time_sec, reason, ...
    'VariableNames', { ...
        'system', 'eeg_chunk_index', 'edf_chunk_index', ...
        'start_anchor_event_index', 'end_anchor_event_index', ...
        'start_anchor_latency', 'end_anchor_latency', ...
        'start_anchor_time_sec', 'end_anchor_time_sec', 'reason'});

end

