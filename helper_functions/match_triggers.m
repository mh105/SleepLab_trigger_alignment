%%
function [startup_mode, cycle_start_event_index] = ...
    classify_edf_startup(edf_input, event_count)

startup_mode = "legacy_startup";
cycle_start_event_index = 1;
if ~isfield(edf_input, 'validation_sequence_count')
    return
end

required_fields = { ...
    'validation_sequences', ...
    'pre_authoritative_validation_event_count'};
assert(all(isfield(edf_input, required_fields)), ...
    'match_triggers:InvalidStartupMetadata', ...
    'EDF validation metadata is incomplete.')

validation_sequence_count = edf_input.validation_sequence_count;
pre_alignment_event_count = ...
    edf_input.pre_authoritative_validation_event_count;
assert(isnumeric(validation_sequence_count) && ...
    isscalar(validation_sequence_count) && ...
    isfinite(validation_sequence_count) && ...
    validation_sequence_count >= 0 && ...
    validation_sequence_count == fix(validation_sequence_count) && ...
    istable(edf_input.validation_sequences) && ...
    height(edf_input.validation_sequences) == validation_sequence_count, ...
    'match_triggers:InvalidStartupMetadata', ...
    'EDF validation-sequence metadata is inconsistent.')
assert(isnumeric(pre_alignment_event_count) && ...
    isscalar(pre_alignment_event_count) && ...
    isfinite(pre_alignment_event_count) && ...
    pre_alignment_event_count >= 0 && ...
    pre_alignment_event_count == fix(pre_alignment_event_count), ...
    'match_triggers:InvalidStartupMetadata', ...
    'EDF pre-validation event count must be a nonnegative integer.')

if validation_sequence_count == 0
    assert(pre_alignment_event_count == 0, ...
        'match_triggers:InvalidStartupMetadata', ...
        'EDF without validation cannot have pre-validation events.')
    startup_mode = "no_validation";
    return
end

assert(pre_alignment_event_count < event_count, ...
    'match_triggers:InvalidStartupMetadata', ...
    'No regular EDF triggers remain after the final validation sequence.')
cycle_start_event_index = pre_alignment_event_count + 1;
if pre_alignment_event_count == 0
    startup_mode = "normal_validation_start";
else
    startup_mode = "restart_at_last_validation";
end

end

