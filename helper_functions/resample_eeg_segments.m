function resampled_eeg_segment_data = resample_eeg_segments( ...
    eeg_segment_data, matched_segments, edf_input, plot_sanity_check)
%RESAMPLE_EEG_SEGMENTS Resample HD-EEG segments onto the EDF scalp clock.
%   The EDF time axis is the reference. Each segment's effective HD-EEG
%   sampling rate is calculated from its EEG sample span and its duration
%   on the EDF clock. Each channel is converted to double, mean-centered,
%   and zero-phase high-pass filtered with an 80-dB stopband at 0.15 Hz
%   and a 0.30-Hz passband edge. A low-pass-scaled Kaiser-windowed sinc
%   resampler then applies the 120-Hz passband / 128-Hz stopband
%   antialiasing response while evaluating the signal directly on the
%   exact EDF scalp sample grid.
%   RESAMPLE_EEG_SEGMENTS(..., PLOT_SANITY_CHECK) creates a 5-by-2 trace
%   comparison using the middle 30 seconds of the first 10 minutes, plus a
%   Welch-spectrum figure for each matched segment. These plots include
%   only the 10 EDF scalp and mastoid channels, not auxiliary VEOGL data.

if nargin < 4
    plot_sanity_check = false;
end

edf_Fs = edf_input.Fs;
edf_trigger_Fs = edf_input.trigger_Fs;
aligned_eeg_channel_names = string( ...
    edf_input.aligned_eeg_channel_names);

assert(exist('buttord', 'file') == 2 && ...
    exist('butter', 'file') == 2 && ...
    exist('zp2sos', 'file') == 2 && ...
    exist('filtfilt', 'file') == 2 && ...
    exist('kaiserord', 'file') == 2 && ...
    exist('kaiser', 'file') == 2, ...
    'resample_eeg_segments:MissingSignalProcessingToolbox', ...
    ['The Signal Processing Toolbox must be on the MATLAB path before ' ...
    'resampling.'])

n_segments = height(matched_segments);
assert(numel(eeg_segment_data) == n_segments, ...
    'resample_eeg_segments:SegmentCountMismatch', ...
    'The EEG cell array must contain one entry per matched segment.')

scalp_samples_per_trigger_sample = edf_Fs / edf_trigger_Fs;
ratio_tolerance = 10 * eps(max(abs( ...
    scalp_samples_per_trigger_sample), 1));
assert(abs(scalp_samples_per_trigger_sample - ...
    round(scalp_samples_per_trigger_sample)) <= ratio_tolerance, ...
    'resample_eeg_segments:NonintegerEdfRateRatio', ...
    ['The EDF scalp sampling rate must be an integer multiple of the ' ...
    'EDF trigger sampling rate.'])

resampled_eeg_segment_data = cell(n_segments, 1);

for segment_i = 1:n_segments
    assert(size(eeg_segment_data{segment_i}, 1) == ...
        numel(aligned_eeg_channel_names), ...
        'resample_eeg_segments:ChannelCountMismatch', ...
        ['EEG segment %d must contain one row per aligned EEG channel ' ...
        'name.'], segment_i)

    eeg_sample_span = double( ...
        matched_segments.eeg_end_sample(segment_i) - ...
        matched_segments.eeg_start_sample(segment_i));
    assert(size(eeg_segment_data{segment_i}, 2) == eeg_sample_span + 1, ...
        'resample_eeg_segments:UnexpectedEegSegmentLength', ...
        'EEG segment %d does not match its reported sample bounds.', ...
        segment_i)

    edf_trigger_sample_span = double( ...
        matched_segments.edf_end_sample(segment_i) - ...
        matched_segments.edf_start_sample(segment_i));
    edf_duration_sec = edf_trigger_sample_span / edf_trigger_Fs;
    effective_hd_eeg_Fs = eeg_sample_span / edf_duration_sec;

    target_sample_span = edf_trigger_sample_span * ...
        scalp_samples_per_trigger_sample;
    target_span_tolerance = 10 * eps(max(abs(target_sample_span), 1));
    assert(abs(target_sample_span - round(target_sample_span)) <= ...
        target_span_tolerance, ...
        'resample_eeg_segments:NonintegerTargetSampleSpan', ...
        'EDF segment %d does not map to an integer scalp sample span.', ...
        segment_i)
    expected_sample_count = round(target_sample_span) + 1;

    % 1. Convert every channel to double before filtering and resampling.
    processed_eeg_segment = double(eeg_segment_data{segment_i});

    % 2. Mean-center each channel to remove its constant (DC) offset.
    processed_eeg_segment = processed_eeg_segment - ...
        mean(processed_eeg_segment, 2);

    % 3. Apply the 80-dB zero-phase high-pass (0.15-Hz stop, 0.30-Hz pass).
    processed_eeg_segment = apply_eeg_highpass_filter( ...
        processed_eeg_segment, effective_hd_eeg_Fs);

    % 4. Apply integrated anti-aliasing and sample on the exact EDF grid.
    resampled_segment = resample_with_antialiasing_kaiser_sinc( ...
        processed_eeg_segment, eeg_sample_span, ...
        round(target_sample_span), effective_hd_eeg_Fs, edf_Fs);

    assert(size(resampled_segment, 2) == expected_sample_count, ...
        'resample_eeg_segments:UnexpectedResampledLength', ...
        ['Resampled EEG segment %d contains %d samples; the matched EDF ' ...
        'scalp interval requires %d samples.'], ...
        segment_i, size(resampled_segment, 2), expected_sample_count)
    resampled_eeg_segment_data{segment_i} = resampled_segment;

    if plot_sanity_check
        output_time_sec = (0:(expected_sample_count - 1))' / edf_Fs;
        plot_context_sample_span = min( ...
            round(10 * 60 * edf_Fs), expected_sample_count - 1);
        trace_sample_span = min( ...
            round(30 * edf_Fs), plot_context_sample_span);
        first_output_plot_sample = floor( ...
            (plot_context_sample_span - trace_sample_span) / 2);
        last_output_plot_sample = ...
            first_output_plot_sample + trace_sample_span;
        trace_start_sec = first_output_plot_sample / edf_Fs;
        trace_end_sec = last_output_plot_sample / edf_Fs;
        first_input_plot_sample = max(0, floor( ...
            trace_start_sec * effective_hd_eeg_Fs));
        last_input_plot_sample = min(eeg_sample_span, ceil( ...
            trace_end_sec * effective_hd_eeg_Fs));
        % Apply the same Kaiser anti-aliasing response on the unchanged
        % input grid so the trace comparison isolates resampling effects.
        antialiased_eeg_segment = apply_antialiasing_filter( ...
            processed_eeg_segment, eeg_sample_span, ...
            first_input_plot_sample, last_input_plot_sample, ...
            effective_hd_eeg_Fs, edf_Fs);
        input_time_sec = ...
            (first_input_plot_sample:last_input_plot_sample)' / ...
            effective_hd_eeg_Fs;
        plot_resampling_sanity_checks( ...
            antialiased_eeg_segment, ...
            resampled_eeg_segment_data{segment_i}, ...
            input_time_sec, output_time_sec, ...
            trace_start_sec, trace_end_sec, ...
            aligned_eeg_channel_names, edf_Fs, segment_i)
    end
end

assert(numel(resampled_eeg_segment_data) == height(matched_segments), ...
    'Resampling did not return one HD-EEG cell per matched segment.')

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% END OF RESAMPLE_EEG_SEGMENTS (MAIN FUNCTION)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
end

