function [final_eeg_data, edf_eeg_channel_names, ...
    aligned_eeg_channel_names, ...
    signalHeader_all, signalCell_all] = make_fixture(n_samples)

if nargin < 1
    n_samples = 5;
end

edf_eeg_channel_names = { ...
    'Fp1', 'C4', 'O1', 'F3', 'Fp2', 'O2', 'F4', 'C3'};
aligned_eeg_channel_names = [ ...
    {'VEOGL', 'M2'}, edf_eeg_channel_names, {'M1'}];
final_eeg_data = reshape( ...
    1:(numel(aligned_eeg_channel_names) * n_samples), ...
    numel(aligned_eeg_channel_names), n_samples);

signal_labels = { ...
    'PAP Pres', 'E1', 'F4:M1', 'Fp1', 'E2', 'M2', ...
    'Fp2:M1', 'C3', 'M1', 'C3:M2', 'C4', 'Fp2', ...
    'O1:M2', 'O1', 'F3', 'F4', 'Fp1:M2', 'F3:M2', ...
    'C4:M1', 'O2', 'O2:M1', ...
    'E2:M1', 'E1:M2', 'E2:M2', 'EDF Annotations'};
for channel_i = numel(signal_labels):-1:1
    signalHeader_all(channel_i).signal_labels = signal_labels{channel_i};
    signalHeader_all(channel_i).physical_min = -1800;
    signalHeader_all(channel_i).physical_max = 1800;
    signalHeader_all(channel_i).digital_min = -32768;
    signalHeader_all(channel_i).digital_max = 32767;
end

signalCell_all = cell(1, numel(signal_labels));
for channel_i = 1:numel(signal_labels)
    channel_data = -(channel_i * 100 + (1:n_samples));
    if mod(channel_i, 2) == 0
        channel_data = channel_data.';
    end
    signalCell_all{channel_i} = channel_data;
end

signalCell_all{strcmp(signal_labels, 'PAP Pres')} = single([10; 20]);
signalCell_all{strcmp(signal_labels, 'E1')} = ...
    int16(101:(100 + n_samples));
signalCell_all{strcmp(signal_labels, 'E2')} = ...
    single((201:(200 + n_samples)).');
signalCell_all{strcmp(signal_labels, 'M1')} = ...
    (100:100:(100 * n_samples)).';
signalCell_all{strcmp(signal_labels, 'M2')} = ...
    (-50:10:(-50 + 10 * (n_samples - 1))).';
signalCell_all{end} = uint8([1, 2, 3]);

for channel_i = 1:numel(edf_eeg_channel_names)
    edf_index = strcmp( ...
        signal_labels, edf_eeg_channel_names{channel_i});
    target_data = 1000 * channel_i + (1:n_samples);
    if mod(channel_i, 2) == 1
        target_data = target_data.';
    end
    signalCell_all{edf_index} = target_data;
end

end

function reference_channel_names = reference_for_scalp_channels( ...
    scalp_channel_names)

reference_rule_active_names = { ...
    'Fp1', 'Fp2', 'F3', 'F4', 'C3', 'C4', 'O1', 'O2'};
reference_rule_mastoid_names = { ...
    'M2', 'M1', 'M2', 'M1', 'M2', 'M1', 'M2', 'M1'};
[~, reference_rule_index] = ismember( ...
    scalp_channel_names, reference_rule_active_names);
reference_channel_names = ...
    reference_rule_mastoid_names(reference_rule_index);

end
