function [final_eeg_data, edf_eeg_channel_names, ...
    aligned_eeg_channel_names, ...
    signalHeader_all, signalCell_all] = make_fixture
edf_eeg_channel_names = { ...
    'M2', 'Fp1', 'C4', 'O1', 'F3', ...
    'M1', 'Fp2', 'O2', 'F4', 'C3'};
aligned_eeg_channel_names = [{'VEOGL'}, edf_eeg_channel_names];
n_samples = 5;
final_eeg_data = single(reshape( ...
    1:(numel(aligned_eeg_channel_names) * n_samples), ...
    numel(aligned_eeg_channel_names), n_samples));

signal_labels = { ...
    'PAP Pres', 'E2:M1', 'E1:M2', 'E2:M2', ...
    'F4:M1', 'C4:M1', 'O2:M1', ...
    'Fp1', 'Fp2', 'C3', 'C4', 'M1', 'M2', ...
    'O1', 'O2', 'F3', 'F4', 'Fp1:M2', 'Fp2:M1', ...
    'F3:M2', 'C3:M2', 'O1:M2', 'EDF Annotations'};
for channel_i = numel(signal_labels):-1:1
    signalHeader_all(channel_i).signal_labels = signal_labels{channel_i};
end

signalCell_all = repmat( ...
    {single(-ones(n_samples, 1))}, 1, numel(signal_labels));
signalCell_all{1} = [10; 20];
signalCell_all{strcmp(signal_labels, 'E2:M1')} = ...
    double([101 102 103 104 105]);
signalCell_all{strcmp(signal_labels, 'E1:M2')} = ...
    single([201; 202; 203; 204; 205]);
signalCell_all{strcmp(signal_labels, 'E2:M2')} = ...
    int16([301 302 303 304 305]);
signalCell_all{end} = uint8([1 2 3]);
end
