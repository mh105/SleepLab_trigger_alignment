function verify_report_rows(testCase, report_output, expected_derivations)

channel_names = canonical_direct_channel_names;
verifyTrue(testCase, contains(report_output, ...
    'Final output EDF channel bounds report'))
verifyTrue(testCase, contains(report_output, 'OutputDerivation'))
verifyTrue(testCase, contains(report_output, ...
    'PercentOutsideBoundsWithinMatchedSamples (%)'))
verifyFalse(testCase, contains(report_output, '<html>'))

row_position = zeros(size(channel_names));
for channel_i = 1:numel(channel_names)
    channel_pattern = regexptranslate( ...
        'escape', ['"' channel_names{channel_i} '"']);
    derivation_pattern = regexptranslate( ...
        'escape', ['"' char(expected_derivations(channel_i)) '"']);
    row_pattern = [channel_pattern '\s+' derivation_pattern];
    row_position(channel_i) = regexp( ...
        report_output, row_pattern, 'once');
    verifyNotEmpty(testCase, row_position(channel_i))
end
verifyGreaterThan(testCase, diff(row_position), zeros(1, 11))

end

