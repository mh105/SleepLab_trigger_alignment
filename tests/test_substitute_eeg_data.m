function [report_output, signalCell_final, figure_handle, ...
    percent_outside_bounds] = capture_substitute_eeg_data(varargin)

substitution_call = @() substitute_eeg_data(varargin{:}); %#ok<NASGU>
[report_output, signalCell_final, figure_handle, ...
    percent_outside_bounds] = evalc('substitution_call()');

