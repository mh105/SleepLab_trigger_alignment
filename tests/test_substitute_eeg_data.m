function testNormalPathUsesClinicalMastoidCompensation(testCase)
[aligned_eeg_data, edf_eeg_channel_names, aligned_eeg_channel_names, ...
    signalHeader_all, signalCell_all, matched_sample_mask] = make_fixture;
signalCell_before = signalCell_all;

[report_output, signalCell_final, figure_handle, percent_outside_bounds] = ...
    capture_substitute_eeg_data( ...
    aligned_eeg_data, aligned_eeg_channel_names, edf_eeg_channel_names, ...
    signalHeader_all, signalCell_all, false, matched_sample_mask, false);

signal_labels = {signalHeader_all.signal_labels};
psg_eeg_channel_names = canonical_psg_eeg_channel_names;
reference_channel_names = reference_for_psg_eeg_channels( ...
    psg_eeg_channel_names);
for channel_i = 1:numel(psg_eeg_channel_names)
    active_index = strcmp( ...
        aligned_eeg_channel_names, psg_eeg_channel_names{channel_i});
    aligned_reference_index = strcmp( ...
        aligned_eeg_channel_names, reference_channel_names{channel_i});
    clinical_reference_index = strcmp( ...
        signal_labels, reference_channel_names{channel_i});
    edf_index = strcmp(signal_labels, psg_eeg_channel_names{channel_i});
    expected = ...
        aligned_eeg_data(active_index, :) - ...
        aligned_eeg_data(aligned_reference_index, :) + ...
        reshape(signalCell_all{clinical_reference_index}, 1, []);

    verifyEqual(testCase, signalCell_final{edf_index}, ...
        reshape(expected, size(signalCell_all{edf_index})))
    verifySize(testCase, signalCell_final{edf_index}, ...
        size(signalCell_all{edf_index}))
end

preserved_direct_names = {'M1', 'M2', 'E1', 'E2'};
for channel_i = 1:numel(preserved_direct_names)
    edf_index = strcmp(signal_labels, preserved_direct_names{channel_i});
    verifyEqual(testCase, signalCell_final{edf_index}, ...
        signalCell_all{edf_index})
    verifyClass(testCase, signalCell_final{edf_index}, ...
        class(signalCell_all{edf_index}))
end
verify_unrelated_cells_unchanged( ...
    testCase, signal_labels, signalCell_before, signalCell_final, ...
    psg_eeg_channel_names)
verifyEqual(testCase, signalCell_all, signalCell_before)
verifyEmpty(testCase, figure_handle)
verifyEqual(testCase, percent_outside_bounds, zeros(12, 1))

expected_derivations = [ ...
    "Aligned Fp1 - Aligned M2 + Clinical M2"; ...
    "Aligned Fp2 - Aligned M1 + Clinical M1"; ...
    "Aligned F3 - Aligned M2 + Clinical M2"; ...
    "Aligned F4 - Aligned M1 + Clinical M1"; ...
    "Aligned C3 - Aligned M2 + Clinical M2"; ...
    "Aligned C4 - Aligned M1 + Clinical M1"; ...
    "Aligned O1 - Aligned M2 + Clinical M2"; ...
    "Aligned O2 - Aligned M1 + Clinical M1"; ...
    "Clinical M1"; ...
    "Clinical M2"; ...
    "Clinical E1"; ...
    "Clinical E2"];
verify_report_rows(testCase, report_output, expected_derivations)
end

