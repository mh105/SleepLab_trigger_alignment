function testSubstitutesDirectAndReferencedChannelsByName(testCase)
[final_eeg_data, edf_eeg_channel_names, aligned_eeg_channel_names, ...
    signalHeader_all, signalCell_all] = make_fixture;

signalCell_final = substitute_eeg_data( ...
    final_eeg_data, edf_eeg_channel_names, aligned_eeg_channel_names, ...
    signalHeader_all, signalCell_all);

signal_labels = {signalHeader_all.signal_labels};
for channel_i = 1:numel(edf_eeg_channel_names)
    aligned_index = find(strcmp( ...
        aligned_eeg_channel_names, edf_eeg_channel_names{channel_i}));
    edf_index = find(strcmp( ...
        signal_labels, edf_eeg_channel_names{channel_i}));
    verifyEqual(testCase, signalCell_final{edf_index}, ...
        final_eeg_data(aligned_index, :).')
    verifyClass(testCase, signalCell_final{edf_index}, 'single')
end

referenced_channel_names = { ...
    'Fp1:M2', 'Fp2:M1', 'F3:M2', 'F4:M1', ...
    'C3:M2', 'C4:M1', 'O1:M2', 'O2:M1'};
active_channel_names = { ...
    'Fp1', 'Fp2', 'F3', 'F4', 'C3', 'C4', 'O1', 'O2'};
reference_channel_names = { ...
    'M2', 'M1', 'M2', 'M1', 'M2', 'M1', 'M2', 'M1'};

for channel_i = 1:numel(referenced_channel_names)
    active_index = find(strcmp( ...
        aligned_eeg_channel_names, active_channel_names{channel_i}));
    reference_index = find(strcmp( ...
        aligned_eeg_channel_names, reference_channel_names{channel_i}));
    edf_index = find(strcmp( ...
        signal_labels, referenced_channel_names{channel_i}));
    expected = final_eeg_data(active_index, :) - ...
        final_eeg_data(reference_index, :);
    verifyEqual(testCase, signalCell_final{edf_index}, expected.')
    verifyClass(testCase, signalCell_final{edf_index}, 'single')
end

verifyEqual(testCase, signalCell_final{1}, signalCell_all{1})
verifyEqual(testCase, signalCell_final{end}, signalCell_all{end})
unchanged_eog_channel_names = {'E2:M1', 'E1:M2', 'E2:M2'};
for channel_i = 1:numel(unchanged_eog_channel_names)
    edf_index = find(strcmp( ...
        signal_labels, unchanged_eog_channel_names{channel_i}));
    verifyEqual(testCase, signalCell_final{edf_index}, ...
        signalCell_all{edf_index})
end
verifySize(testCase, signalCell_final, size(signalCell_all))
end

